/**
 * Draws the home-screen icon and writes it to src/icons.ts as an SVG string and
 * two base64 PNGs.
 *
 * Phones want raster icons at fixed sizes, and the repository keeps no binary
 * files, so the PNGs live in source as text. Drawing them here from the same
 * shapes as the SVG, instead of pasting in an exported image, means a
 * reviewer can see what the base64 is and anyone can regenerate it:
 *
 *   npm run icons
 *
 * Everything stays inside the centre 80% circle, the safe zone Android crops
 * maskable icons to, and the background runs to the edges because iOS and
 * Android both round the corners themselves.
 */
import { writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';

const SIZE = 512;
const BACKGROUND = 0x11;
const INK = 0xff;

const BUBBLE = { x: 124, y: 140, w: 264, h: 196, r: 60 };
const TAIL: Array<[number, number]> = [[172, 320], [236, 320], [150, 392]];
const DOTS = [196, 256, 316].map((cx) => ({ cx, cy: 238, r: 22 }));

function inBubble(x: number, y: number): boolean {
  const { x: left, y: top, w, h, r } = BUBBLE;
  if (x < left || x > left + w || y < top || y > top + h) return false;
  const cx = Math.min(Math.max(x, left + r), left + w - r);
  const cy = Math.min(Math.max(y, top + r), top + h - r);
  return (x - cx) ** 2 + (y - cy) ** 2 <= r * r;
}

function inTail(x: number, y: number): boolean {
  const side = (a: [number, number], b: [number, number]) => (b[0] - a[0]) * (y - a[1]) - (b[1] - a[1]) * (x - a[0]);
  const [a, b, c] = TAIL as [[number, number], [number, number], [number, number]];
  const s1 = side(a, b);
  const s2 = side(b, c);
  const s3 = side(c, a);
  return (s1 >= 0 && s2 >= 0 && s3 >= 0) || (s1 <= 0 && s2 <= 0 && s3 <= 0);
}

function inked(x: number, y: number): boolean {
  if (DOTS.some((d) => (x - d.cx) ** 2 + (y - d.cy) ** 2 <= d.r * d.r)) return false;
  return inBubble(x, y) || inTail(x, y);
}

function iconSvg(): string {
  const { x, y, w, h, r } = BUBBLE;
  const hex = (v: number) => `#${v.toString(16).padStart(2, '0').repeat(3)}`;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}">`,
    `<rect width="${SIZE}" height="${SIZE}" fill="${hex(BACKGROUND)}"/>`,
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${hex(INK)}"/>`,
    `<path d="M${TAIL.map((p) => p.join(' ')).join('L')}Z" fill="${hex(INK)}"/>`,
    ...DOTS.map((d) => `<circle cx="${d.cx}" cy="${d.cy}" r="${d.r}" fill="${hex(BACKGROUND)}"/>`),
    '</svg>',
  ].join('');
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(bytes: Uint8Array): number {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC_TABLE[(c ^ b) & 0xff]! ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Uint8Array): Buffer {
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const out = Buffer.alloc(body.length + 8);
  out.writeUInt32BE(data.length, 0);
  body.copy(out, 4);
  out.writeUInt32BE(crc32(body), body.length + 4);
  return out;
}

/** An 8-bit greyscale PNG, 4×4 supersampled so the curves are smooth. */
function iconPng(px: number): Buffer {
  const scale = SIZE / px;
  const rows: Buffer[] = [];
  let previous = Buffer.alloc(px);
  for (let py = 0; py < px; py++) {
    const row = Buffer.alloc(px);
    for (let qx = 0; qx < px; qx++) {
      let hits = 0;
      for (let sy = 0; sy < 4; sy++) {
        for (let sx = 0; sx < 4; sx++) {
          if (inked((qx + (sx + 0.5) / 4) * scale, (py + (sy + 0.5) / 4) * scale)) hits++;
        }
      }
      row[qx] = Math.round(BACKGROUND + ((INK - BACKGROUND) * hits) / 16);
    }
    // Filter type 2 ("Up") stores each row as its difference from the one
    // above, so the flat background compresses to almost nothing.
    const filtered = Buffer.alloc(px + 1);
    filtered[0] = 2;
    for (let i = 0; i < px; i++) filtered[i + 1] = (row[i]! - previous[i]! + 256) & 0xff;
    rows.push(filtered);
    previous = row;
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(px, 0);
  header.writeUInt32BE(px, 4);
  header[8] = 8; // bit depth
  header[9] = 0; // greyscale
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', deflateSync(Buffer.concat(rows), { level: 9 })),
    chunk('IEND', new Uint8Array(0)),
  ]);
}

const wrap = (b64: string) => b64.match(/.{1,100}/g)!.map((line) => `  '${line}'`).join(' +\n');
const source = `// Generated by \`npm run icons\` (scripts/icons.ts). Change the drawing there, not here.

export const ICON_SVG =
  '${iconSvg()}';

export const ICON_192_PNG =
${wrap(iconPng(192).toString('base64'))};

export const ICON_512_PNG =
${wrap(iconPng(512).toString('base64'))};
`;
writeFileSync(new URL('../src/icons.ts', import.meta.url), source);
console.log('Wrote src/icons.ts');
